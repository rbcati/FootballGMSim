import 'fake-indexeddb/auto';
import { beforeAll, describe, expect, it } from 'vitest';
import { loadWorkerModule, dispatchWorker } from '../../src/testSupport/dynastySoakRunner.js';
import { cache } from '../../src/db/cache.js';
import { DEFAULT_TEAMS } from '../../src/data/default-teams.js';
import { getSalaryInflationMultiplier } from '../../src/core/economy.js';
import { calculateExtensionDemand } from '../../src/core/player.js';
import { getPlayerCapHit } from '../../src/core/teamValidation.js';
import { toWorker, toUI } from '../../src/worker/protocol.js';

beforeAll(async () => { await loadWorkerModule(); await dispatchWorker(toWorker.INIT); }, 60000);
describe.sequential('offseason decision persistence', () => {
  for (const source of ['normal', 'fallback']) it(`${source}: Buffalo decisions, contracts, save isolation and advance`, async () => {
    const boot = async (slotKey) => dispatchWorker(source === 'normal' ? toWorker.NEW_LEAGUE : toWorker.USE_SAFE_STARTER_LEAGUE, { teams: DEFAULT_TEAMS, slotKey, options: { year: 2026, rngSeed: 1808, userTeamId: 0, salaryCap: 500 } });
    const first = await boot('save_slot_1');
    const leagueId = first.payload.activeLeagueId;
    await dispatchWorker(toWorker.LOAD_SAVE, { leagueId });
    cache.setMeta({ phase: 'offseason_resign' });
    // Fallback starter contracts do not expire in year one; age two real generated contracts into this fixture.
    if (source === 'fallback') for (const p of cache.getPlayersByTeam(0).slice(0, 2)) cache.updatePlayer(p.id, { contract: { ...p.contract, years: 1 } });
    const [walk, extend] = cache.getPlayersByTeam(0).filter(p => p.contract?.years <= 1).sort((a,b) => a.contract.baseAnnual - b.contract.baseAnnual);
    expect(walk).toBeTruthy(); expect(extend).toBeTruthy();
    const original = structuredClone(walk);
    expect((await dispatchWorker(toWorker.UPDATE_PLAYER_MANAGEMENT, { playerId: walk.id, teamId: 0, updates: { extensionDecision: 'let_walk' } })).type).toBe(toUI.STATE_UPDATE);
    expect(cache.getPlayer(walk.id)).toMatchObject({ id: original.id, teamId: 0, contract: original.contract, extensionDecision: 'let_walk' });
    await dispatchWorker(toWorker.SAVE_NOW);
    await dispatchWorker(toWorker.LOAD_SAVE, { leagueId });
    expect(cache.getPlayer(walk.id).extensionDecision).toBe('let_walk');
    const old = structuredClone(cache.getPlayer(walk.id).contract);
    const rejected = await dispatchWorker(toWorker.EXTEND_CONTRACT, { playerId: walk.id, teamId: 0, contract: { years: 1, yearsTotal: 1, baseAnnual: 0, guaranteedPct: 0 } });
    expect(rejected.type).toBe(toUI.EXTENSION_RESPONSE);
    expect(['counter', 'declined']).toContain(rejected.payload.status);
    expect(cache.getPlayer(walk.id).contract).toEqual(old);
    const demand = calculateExtensionDemand(cache.getPlayer(extend.id), 'Normal');
    const years = 5;
    const contract = { signingBonus: demand.signingBonus, years, yearsTotal: years, baseAnnual: demand.baseAnnual * getSalaryInflationMultiplier(cache.getMeta().economy) * 2, guaranteedPct: 0.95 };
    const cap = cache.getTeam(0).capUsed;
    const priorHit = getPlayerCapHit(cache.getPlayer(extend.id));
    const accepted = await dispatchWorker(toWorker.EXTEND_CONTRACT, { playerId: extend.id, teamId: 0, contract });
    expect(accepted.payload.status, JSON.stringify(accepted.payload)).toBe('accepted');
    expect(cache.getPlayer(extend.id)).toMatchObject({ id: extend.id, contract, extensionDecision: 'extended' });
    expect(cache.getTeam(0).capUsed).toBeCloseTo(cap - priorHit + getPlayerCapHit(cache.getPlayer(extend.id)), 4);
    await dispatchWorker(toWorker.SAVE_NOW);
    const second = await boot('save_slot_2');
    const secondIds = cache.getPlayersByTeam(0).map(p => p.id);
    expect(cache.getPlayersByTeam(0).some(p => p.extensionDecision === 'let_walk')).toBe(false);
    await dispatchWorker(toWorker.LOAD_SAVE, { leagueId });
    expect(cache.getPlayer(walk.id).extensionDecision).toBe('let_walk');
    expect(cache.getPlayer(extend.id).contract).toMatchObject(contract);
    const advanced = await dispatchWorker(toWorker.ADVANCE_OFFSEASON, {}, { timeoutMs: 120000 });
    expect(advanced.type).toBe(toUI.OFFSEASON_PHASE);
    expect(cache.getMeta().phase).toBe('free_agency');
    await dispatchWorker(toWorker.SAVE_NOW);
    await dispatchWorker(toWorker.LOAD_SAVE, { leagueId });
    expect(cache.getMeta().phase).toBe('free_agency');
    await dispatchWorker(toWorker.LOAD_SAVE, { leagueId: second.payload.activeLeagueId });
    expect(new Set(cache.getPlayersByTeam(0).map(p => p.id))).toEqual(new Set(secondIds));
    expect(cache.getPlayersByTeam(0).some(p => p.extensionDecision === 'let_walk')).toBe(false);
  }, 180000);
});
